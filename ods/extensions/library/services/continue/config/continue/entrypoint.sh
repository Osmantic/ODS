#!/bin/sh
# ODS — Continue config generator
# Runs as part of nginx's docker-entrypoint.d/ on container start.
# Writes a Continue config.yaml with the endpoint reachable from the IDE.

set -eu

WEBROOT="${CONTINUE_WEBROOT:-/usr/share/nginx/html}"
: "${CONTINUE_API_BASE:?Set CONTINUE_API_BASE to the full API base reachable from your IDE, including /v1 or /api/v1}"
CONTINUE_API_BASE="${CONTINUE_API_BASE%/}"

# This public config contains an endpoint, never credentials. Reject characters
# that would change the YAML structure or turn an API base into a query URL.
case "$CONTINUE_API_BASE" in
    http://?*|https://?*) ;;
    *) echo "[continue-init] CONTINUE_API_BASE must be an HTTP(S) API base." >&2; exit 1 ;;
esac
case "$CONTINUE_API_BASE" in
    *[[:space:]\'\"\\\?\#\@]*|http:///*|https:///*)
        echo "[continue-init] CONTINUE_API_BASE must not contain whitespace, credentials, quotes, a query or fragment." >&2
        exit 1
        ;;
esac

mkdir -p "${WEBROOT}"

# Write the Continue config.yaml that IDE clients will fetch
cat > "${WEBROOT}/config.yaml" <<EOF
# Continue config — auto-generated by ODS
# Download this file and merge its models into ~/.continue/config.yaml.
# Add any provider API key in your private IDE configuration only.
#
# https://docs.continue.dev/reference

name: ODS Assistant
version: 1.0.0
schema: v1

models:
  - name: Local LLM (ODS)
    provider: openai
    apiBase: '${CONTINUE_API_BASE}'
    model: AUTODETECT
    roles:
      - chat
      - edit
      - apply

  - name: Local LLM Autocomplete (ODS)
    provider: openai
    apiBase: '${CONTINUE_API_BASE}'
    model: AUTODETECT
    roles:
      - autocomplete

context:
  - provider: code
  - provider: docs
  - provider: diff
  - provider: terminal
  - provider: problems
  - provider: folder
  - provider: codebase
EOF

# Write a minimal health sentinel (nginx serves /health via config)
echo "ODS Continue config ready." > "${WEBROOT}/index.html"

echo "[continue-init] config.yaml written to ${WEBROOT}"
