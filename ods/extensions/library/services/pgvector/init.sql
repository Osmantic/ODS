\set ON_ERROR_STOP on
\getenv app_password PGVECTOR_APP_PASSWORD
CREATE EXTENSION IF NOT EXISTS vector;
CREATE ROLE ods_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'app_password';
\unset app_password
REVOKE ALL ON DATABASE vectors FROM PUBLIC;
GRANT CONNECT ON DATABASE vectors TO ods_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO ods_app;
CREATE SCHEMA project AUTHORIZATION ods_app;
ALTER ROLE ods_app IN DATABASE vectors SET search_path TO project, public;
